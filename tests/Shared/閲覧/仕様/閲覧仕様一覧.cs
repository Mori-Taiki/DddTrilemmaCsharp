using static Demo.Tests.ストーリーの条件;
using static Demo.Tests.フォロー状況;
using static Demo.Tests.会員資格;
using static Demo.Tests.作者との関係;
using static Demo.Tests.取得する事実;
using static Demo.Tests.購入状況;
using static Demo.Tests.閲覧の期待値;

namespace Demo.Tests;

// 期待値は業務仕様から明示する。ドメイン実装を呼んだり入力から計算したりしない。
public sealed class 閲覧仕様一覧 : TheoryData<閲覧仕様>
{
    public 閲覧仕様一覧()
    {
        Add(
            new(
                "作者本人は全体公開の無料ストーリーを追加取得なしで読める",
                入力: new(全体公開の無料ストーリー, new(作者本人, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "作者本人は全体公開の有料ストーリーを追加取得なしで読める",
                入力: new(全体公開の有料ストーリー, new(作者本人, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "作者本人はフォロワー限定の無料ストーリーを追加取得なしで読める",
                入力: new(
                    フォロワー限定の無料ストーリー,
                    new(作者本人, 未フォロー, 一般会員, 未購入)
                ),
                期待: 許可される()
            )
        );
        Add(
            new(
                "作者本人はフォロワー限定の有料ストーリーを追加取得なしで読める",
                入力: new(
                    フォロワー限定の有料ストーリー,
                    new(作者本人, 未フォロー, 一般会員, 未購入)
                ),
                期待: 許可される()
            )
        );
        Add(
            new(
                "全体公開の無料ストーリーは作者以外も追加取得なしで読める",
                入力: new(全体公開の無料ストーリー, new(作者以外, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "フォロワー限定の無料ストーリーはフォロワーなら読める",
                入力: new(
                    フォロワー限定の無料ストーリー,
                    new(作者以外, フォロー済み, 一般会員, 未購入)
                ),
                期待: 許可される(フォロー確認)
            )
        );
        Add(
            new(
                "フォロワー限定の無料ストーリーは非フォロワーを拒否する",
                入力: new(
                    フォロワー限定の無料ストーリー,
                    new(作者以外, 未フォロー, 一般会員, 未購入)
                ),
                期待: 未フォローで拒否される(フォロー確認)
            )
        );
        Add(
            new(
                "全体公開の有料ストーリーはVIPなら購入確認なしで読める",
                入力: new(全体公開の有料ストーリー, new(作者以外, 未フォロー, VIP会員, 未購入)),
                期待: 許可される(VIP会員確認)
            )
        );
        Add(
            new(
                "全体公開の有料ストーリーは一般会員でも購入済みなら読める",
                入力: new(全体公開の有料ストーリー, new(作者以外, 未フォロー, 一般会員, 購入済み)),
                期待: 許可される(VIP会員確認, 購入確認)
            )
        );
        Add(
            new(
                "全体公開の有料ストーリーは未購入の一般会員を拒否する",
                入力: new(全体公開の有料ストーリー, new(作者以外, 未フォロー, 一般会員, 未購入)),
                期待: 未購入で拒否される(VIP会員確認, 購入確認)
            )
        );
        Add(
            new(
                "フォロワー限定の有料ストーリーはフォロー済みVIPなら購入確認なしで読める",
                入力: new(
                    フォロワー限定の有料ストーリー,
                    new(作者以外, フォロー済み, VIP会員, 未購入)
                ),
                期待: 許可される(フォロー確認, VIP会員確認)
            )
        );
        Add(
            new(
                "フォロワー限定の有料ストーリーはフォロー済みで購入済みの一般会員なら読める",
                入力: new(
                    フォロワー限定の有料ストーリー,
                    new(作者以外, フォロー済み, 一般会員, 購入済み)
                ),
                期待: 許可される(フォロー確認, VIP会員確認, 購入確認)
            )
        );
        Add(
            new(
                "フォロワー限定の有料ストーリーはフォロー済みでも未購入の一般会員を拒否する",
                入力: new(
                    フォロワー限定の有料ストーリー,
                    new(作者以外, フォロー済み, 一般会員, 未購入)
                ),
                期待: 未購入で拒否される(フォロー確認, VIP会員確認, 購入確認)
            )
        );
        Add(
            new(
                "非フォロワーはVIPでもフォロワー限定ストーリーを読めない",
                入力: new(
                    フォロワー限定の有料ストーリー,
                    new(作者以外, 未フォロー, VIP会員, 未購入)
                ),
                期待: 未フォローで拒否される(フォロー確認)
            )
        );
        Add(
            new(
                "非フォロワーは購入済みでもフォロワー限定ストーリーを読めない",
                入力: new(
                    フォロワー限定の有料ストーリー,
                    new(作者以外, 未フォロー, 一般会員, 購入済み)
                ),
                期待: 未フォローで拒否される(フォロー確認)
            )
        );
    }
}
