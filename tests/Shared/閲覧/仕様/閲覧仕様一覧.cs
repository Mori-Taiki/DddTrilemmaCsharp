using static Demo.Tests.フォロー状況;
using static Demo.Tests.会員資格;
using static Demo.Tests.作品の条件;
using static Demo.Tests.作者との関係;
using static Demo.Tests.取得する事実;
using static Demo.Tests.購入状況;
using static Demo.Tests.閲覧の期待値;

namespace Demo.Tests;

// 期待値は業務仕様から明示する。ドメイン実装を呼んだり入力から計算したりしない。
public sealed class 閲覧仕様一覧 : TheoryData<閲覧仕様>
{
    public 閲覧仕様一覧()
    {
        Add(
            new(
                "作者本人は全体公開の無料作品を追加取得なしで読める",
                入力: new(全体公開の無料作品, new(作者本人, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "作者本人は全体公開の有料作品を追加取得なしで読める",
                入力: new(全体公開の有料作品, new(作者本人, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "作者本人はフォロワー限定の無料作品を追加取得なしで読める",
                入力: new(フォロワー限定の無料作品, new(作者本人, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "作者本人はフォロワー限定の有料作品を追加取得なしで読める",
                入力: new(フォロワー限定の有料作品, new(作者本人, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "無料公開は作者以外も追加取得なしで読める",
                入力: new(全体公開の無料作品, new(作者以外, 未フォロー, 一般会員, 未購入)),
                期待: 許可される()
            )
        );
        Add(
            new(
                "無料限定はフォロワーが読める",
                入力: new(フォロワー限定の無料作品, new(作者以外, フォロー済み, 一般会員, 未購入)),
                期待: 許可される(フォロー確認)
            )
        );
        Add(
            new(
                "無料限定は非フォロワーを拒否する",
                入力: new(フォロワー限定の無料作品, new(作者以外, 未フォロー, 一般会員, 未購入)),
                期待: フォロー不足で拒否される(フォロー確認)
            )
        );
        Add(
            new(
                "有料公開はVIPなら購入確認なしで読める",
                入力: new(全体公開の有料作品, new(作者以外, 未フォロー, VIP会員, 未購入)),
                期待: 許可される(会員確認)
            )
        );
        Add(
            new(
                "有料公開は一般会員も購入済みなら読める",
                入力: new(全体公開の有料作品, new(作者以外, 未フォロー, 一般会員, 購入済み)),
                期待: 許可される(会員確認, 購入確認)
            )
        );
        Add(
            new(
                "有料公開は未購入の一般会員を拒否する",
                入力: new(全体公開の有料作品, new(作者以外, 未フォロー, 一般会員, 未購入)),
                期待: 未購入で拒否される(会員確認, 購入確認)
            )
        );
        Add(
            new(
                "有料限定はフォロー済みVIPなら購入確認なしで読める",
                入力: new(フォロワー限定の有料作品, new(作者以外, フォロー済み, VIP会員, 未購入)),
                期待: 許可される(フォロー確認, 会員確認)
            )
        );
        Add(
            new(
                "有料限定はフォロー済み購入者が読める",
                入力: new(
                    フォロワー限定の有料作品,
                    new(作者以外, フォロー済み, 一般会員, 購入済み)
                ),
                期待: 許可される(フォロー確認, 会員確認, 購入確認)
            )
        );
        Add(
            new(
                "有料限定はフォロー済みでも未購入の一般会員を拒否する",
                入力: new(フォロワー限定の有料作品, new(作者以外, フォロー済み, 一般会員, 未購入)),
                期待: 未購入で拒否される(フォロー確認, 会員確認, 購入確認)
            )
        );
        Add(
            new(
                "非フォロワーはVIPでも限定作品を読めない",
                入力: new(フォロワー限定の有料作品, new(作者以外, 未フォロー, VIP会員, 未購入)),
                期待: フォロー不足で拒否される(フォロー確認)
            )
        );
        Add(
            new(
                "非フォロワーは購入済みでも限定作品を読めない",
                入力: new(フォロワー限定の有料作品, new(作者以外, 未フォロー, 一般会員, 購入済み)),
                期待: フォロー不足で拒否される(フォロー確認)
            )
        );
    }
}
